// Exécute le vrai cart.js avec un DOM ciblé : aucune mutation du panier réel.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../../Public/assets/js/cart.js'), 'utf8');
let maximumStock = 20;
const piece = (text) => ({innerHTML: text, textContent: text});
const makeRow = (quantity) => {
  const input = {value: String(quantity), defaultValue: String(quantity), min: '1', max: String(maximumStock), disabled: false};
  const buttons = [{dataset: {cartQuantityChange: '-1'}, disabled: quantity <= 1}, {dataset: {cartQuantityChange: '1'}, disabled: quantity >= maximumStock}];
  const image = {attrs: {src: '/own.jpg', alt: 'Sac'}, getAttribute(key) {return this.attrs[key];}, setAttribute(key, value) {this.attrs[key] = value;}};
  const parts = {'[data-cart-quantity-input]': input, '.cart-item__title': piece('Sac'), '.cart-item__prices': piece('$25.00'), '.cart-item__availability': piece('En stock'), img: image};
  return {dataset: {productVariantId: '1'}, classList: {contains: () => false}, attrs: {}, setAttribute(key, value) {this.attrs[key] = value;}, removeAttribute(key) {delete this.attrs[key];}, querySelector: key => parts[key], querySelectorAll: () => buttons};
};
const fragment = (quantity) => {
  const row = makeRow(quantity), summary = piece(`$${quantity * 25}.00`), header = piece(`${quantity} article(s)`);
  return {row, querySelectorAll: () => [row], querySelector: key => key === '.cart-summary' ? summary : header};
};

(async () => {
  let quantity = 1, renders = 0, motions = 0, sets = 0, rejectMutation = false, gate, failRead = false, loseAck = false;
  let tree;
  const content = {get childElementCount() {return tree ? 1 : 0;}, set innerHTML(html) {renders++; tree = fragment(Number(html));}, querySelectorAll: key => tree?.querySelectorAll(key) || [], querySelector: key => tree?.querySelector(key)};
  const loader = {hidden: false}; const results = {setAttribute() {}};
  const pageHandlers = {}, globalHandlers = {};
  const page = {querySelector: key => ({'[data-cart-results]': results, '[data-cart-content]': content, '[data-cart-loader]': loader})[key], addEventListener: (name, fn) => {pageHandlers[name] = fn;}};
  const notifications = [];
  const store = {items: () => [{id: 1, quantity}], serialize: () => `1:${quantity}`, replace() {}, refresh: async () => ({}), async setQuantity(id, next) {sets++; if(rejectMutation) throw new Error('Stock insuffisant'); quantity = Math.min(maximumStock,next); if(loseAck){loseAck=false;throw new Error('Réponse perdue après écriture');} globalHandlers['cart:server-updated']();}};
  const window = {CartStore: store, addEventListener: (name, fn) => {globalHandlers[name] = fn;}, MotionSystem: {refresh() {motions++;}, fire: data => {notifications.push(data);}}, lucide: {createIcons() {}}};
  const badge = {textContent: ''};
  const document = {querySelector: () => page, querySelectorAll: key => key === '[data-cart-count]' ? [badge] : [], createElement() {let parsed;return {set innerHTML(html) {parsed = fragment(Number(html));}, querySelectorAll: key => parsed.querySelectorAll(key), querySelector: key => parsed.querySelector(key)};}};
  const fetch = async (url, options) => {if(gate) await gate;return {ok: !failRead, json: async () => ({html: String(quantity), items: [{id: 1, quantity}], notice: null})};};
  vm.runInNewContext(source, {window, document, fetch, AbortController});
  const flush = async () => {for(let i=0;i<30;i++)await Promise.resolve();};
  await flush();
  const original = tree.row, image = original.querySelector('img');
  const click = delta => pageHandlers.click({target: {closest: selector => selector === '[data-cart-item]' ? tree.row : selector === '[data-cart-quantity-change]' ? {dataset: {cartQuantityChange: String(delta)}} : null}});
  assert.equal(renders, 1); assert.equal(motions, 1);
  let release;gate = new Promise(resolve => {release = resolve;});
  await click(1); await click(1); await click(1); await click(-1); await flush();
  assert.equal(sets, 1, 'Une seule mutation active, clic suivant coalescé');
  assert.equal(original.querySelector('[data-cart-quantity-input]').value, '3', 'Réponse immédiate au second clic');
  assert.equal(badge.textContent, '3', 'Compteur provisoire immédiat');
  assert.equal(store.items()[0].quantity, 2, 'CartStore conserve uniquement la réponse serveur');
  assert.equal(loader.hidden, true, 'Pas de loader qui déplace le contenu déjà visible');
  assert.equal(tree.row, original);
  release();gate = null;await flush();
  assert.equal(original.querySelector('[data-cart-quantity-input]').value, '3');
  assert.equal(sets,2,'Deuxième mutation : cible finale uniquement');
  assert.equal(tree.querySelector('.cart-summary').innerHTML, '$75.00');
  assert.match(tree.querySelector('.cart-list__header p').innerHTML, /3/);
  assert.equal(original.querySelector('img'), image, 'Image conservée');
  assert.equal(renders, 1, 'Aucun remplacement global pour une quantité');
  assert.equal(motions, 1, 'Aucune nouvelle entrée Motion');
  await click(-1);await flush();
  assert.equal(original.querySelector('[data-cart-quantity-input]').value, '2');
  assert.equal(tree.querySelector('.cart-summary').innerHTML, '$50.00');
  rejectMutation = true;const input = original.querySelector('[data-cart-quantity-input]');input.value = '3';
  pageHandlers.change({target: {matches: () => true, closest: () => original, value: '3'}});await flush();
  assert.equal(input.value, '2', 'Échec serveur : quantité confirmée conservée');
  assert.ok(notifications.some(data => data.icon === 'error'));
  assert.equal(renders, 1);assert.equal(motions, 1);
  rejectMutation = false;loseAck = true;await click(1);await flush();
  assert.equal(input.value,'3','Réponse perdue après écriture : la relecture serveur prévaut');
  assert.equal(tree.querySelector('.cart-summary').innerHTML,'$75.00');
  await click(99);await flush();
  assert.equal(input.value, '20', 'Limite stock conservée');
  assert.equal(store.items()[0].quantity, 20, 'État servant au compteur synchronisé');
  maximumStock = 3;await click(-1);await flush();
  assert.equal(input.value,'3','Correction serveur réconciliée');
  assert.equal(input.max,'3','Nouvelle limite serveur conservée');
  assert.equal(badge.textContent,'3','Compteur réconcilié');
  assert.equal(renders,1);assert.equal(motions,1);
  failRead = true;await click(-1);await flush();assert.ok(notifications.some(data => data.title === 'Panier indisponible'));
  console.log('CART_QUANTITY_UX_OK (aperçu immédiat, clics coalescés, serveur prioritaire, stock, erreurs réseau, DOM et Motion stables).');
})();
